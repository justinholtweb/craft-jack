 * - `transfer` — `none` (stays in the EEA), `adequacy`, `dpf` (EU–US Data Privacy Framework) or
 *   `scc`. Anything but `none` adds the transfer paragraph.
 * - `essential` — true where the service cannot be switched off without breaking the site, which
 *   is the only case where a cookie clause may claim strict necessity.
 * - `detect` — hints for {@see justinholtweb\jack\services\Detector}: `patterns` are matched
 *   against template source and rendered markup, `plugins` against installed plugin handles,
 *   `env` against environment variable names.
 *
 * `purpose` and `data` are short phrases, not sentences: the clause template supplies the
 * grammar so that forty services do not read like forty different lawyers.
 *
 * @var array<string, array<string, mixed>>
 */

