 * Jack does not keep a hand-written paragraph per service. It keeps the facts a paragraph is made
 * of — who the provider is, where they are, what the data is for, which legal basis carries it,
 * whether it leaves the EEA and how — and {@see justinholtweb\jack\services\Compiler} renders the
